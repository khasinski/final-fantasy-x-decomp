def _rows(layouts, names, base=None):
    """(cid, ts, sym...) rows -> per-container dicts for _unit_syms; base = {sym: offset from ts}."""
    out = []
    for row in layouts:
        syms = dict(zip(names, row[2:]))
        syms.update({k: row[1] + v for k, v in (base or {}).items()})
        out.append((row[0], row[1], syms))
    return out


def _unit_syms(src, rows, size, code_bytes, funcs):
    return {
        "src": src,
        "containers": [cid for cid, _, _ in rows],
        "text_start": rows[0][1],
        "text_end": rows[0][1] + size,
        "discovered_code_bytes": code_bytes,
        "functions": funcs,
        "syms": rows[0][2],
        "container_layouts": [
            {"cid": cid, "text_start": ts, "text_end": ts + size, "syms": syms} for cid, ts, syms in rows
        ],
    }


