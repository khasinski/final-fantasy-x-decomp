def _unit(src, layouts, size, code_bytes, funcs, base_syms=None):
    base_syms = base_syms or {}

    def syms(ts):
        return {n: ts + d for n, d in base_syms.items()}

    return {
        "src": src,
        "containers": [row[0] for row in layouts],
        "text_start": layouts[0][1],
        "text_end": layouts[0][1] + size,
        "discovered_code_bytes": code_bytes,
        "functions": funcs,
        "syms": syms(layouts[0][1]),
        "container_layouts": [
            {"cid": cid, "text_start": ts, "text_end": ts + size, "syms": syms(ts)}
            for cid, ts in layouts
        ],
    }


