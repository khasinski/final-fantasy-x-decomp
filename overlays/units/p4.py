TU15_NOISE = 0x90    # func_01B0A008 (parked: overlays/wip/ovl_09065_sprites_noise.c)
TU15_WAVE = 0x370    # func_01B0A2E8
TU15_END = 0x5F4


def _units_tu15():
    cmd = {
        "src": "overlays/group11/ovl_09065_sprites_cmd.c",
        "cflags": P4_CFLAGS,
        "containers": [r[0] for r in TU15_LAYOUTS],
        "text_start": TU15_LAYOUTS[0][1],
        "text_end": TU15_LAYOUTS[0][1] + TU15_NOISE,
        "discovered_code_bytes": TU15_NOISE,
        "functions": 1,
        "container_layouts": [],
    }
    wave = {
        "src": "overlays/group11/ovl_09065_sprites_wave.c",
        "cflags": P4_CFLAGS,
        "containers": [r[0] for r in TU15_LAYOUTS],
        "text_start": TU15_LAYOUTS[0][1] + TU15_WAVE,
        "text_end": TU15_LAYOUTS[0][1] + TU15_END,
        "discovered_code_bytes": TU15_END - TU15_WAVE,
        "functions": 1,
        "syms": {},
        "container_layouts": [],
    }
    for cid, ts in TU15_LAYOUTS:
        syms = {"func_01B0A008": ts + TU15_NOISE, "func_01B0A2E8": ts + TU15_WAVE}
        cmd["container_layouts"].append(
            {"cid": cid, "text_start": ts, "text_end": ts + TU15_NOISE, "syms": syms})
        wave["container_layouts"].append(
            {"cid": cid, "text_start": ts + TU15_WAVE, "text_end": ts + TU15_END, "syms": {}})
    cmd["syms"] = cmd["container_layouts"][0]["syms"]
    return [cmd, wave]


